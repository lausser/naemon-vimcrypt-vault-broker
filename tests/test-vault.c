/*
 * Tests for the vault module, run by "make check".
 *
 * Like naemon's own lib/test-nsutils.c, the code under test is included, so
 * static functions and variables are reachable. It is linked against the real
 * libnaemon, nothing is stubbed. Error messages are read back from the log
 * file written by libnaemon's nm_log().
 *
 * tests/vim/NN.cfg were encrypted by vim, password "test", plaintext length NN:
 *   vim -Nu NONE -n -es NN.cfg "+set cm=blowfish2" "+set key=test" "+wq"
 * Their plaintexts are listed in kat[] below; check them with "vim tests/vim/16.cfg".
 * All other vault files are generated by encrypt_vault(), which is first
 * proven to produce exactly the bytes vim wrote.
 */
#include "../module.c"
#include <ftw.h>

static const struct {
	const char *file, *text;
} kat[] = {
	{ "16.cfg", "$VAULT1$=012345\n" },
	{ "17.cfg", "$VAULT1$=0123456\n" },
	{ "18.cfg", "$VAULT1$=01234567\n" },
	{ "19.cfg", "$VAULT1$=012345678\n" },
	{ "20.cfg", "$VAULT1$=0123456789\n" },
	{ "21.cfg", "$VAULT1$=0123456789a\n" },
	{ "22.cfg", "$VAULT1$=0123456789ab\n" },
	{ "23.cfg", "$VAULT1$=0123456789abc\n" },
};

static int tests, failures;
static char workdir[] = "/tmp/test-vault.XXXXXX";
static char logpath[PATH_MAX];

static int ok(int success, const char *name)
{
	tests++;
	if(!success)
		failures++;
	printf("%sok %d - %s\n", success ? "" : "not ", tests, name);
	return success;
}

/* write a file below the work directory, creating its parent directories */
static void write_file(const char *rel, const char *data, size_t len)
{
	char path[PATH_MAX];
	FILE *fp;

	snprintf(path, sizeof(path), "%s/%s", workdir, rel);
	nspath_mkdir_p(path, 0700, NSPATH_MKDIR_SKIP_LAST);
	if(!(fp = fopen(path, "w")) || fwrite(data, 1, len, fp) != len || fclose(fp)) {
		printf("Bail out! cannot write %s\n", path);
		exit(1);
	}
}

/* what vim writes with cryptmethod blowfish2: the inverse of decrypt_vault() */
static void encrypt_vault(char *out, const char *salt, const char *seed, const char *text, int len)
{
	char block[8];
	BF_KEY *bfkey;

	master_password = "test";
	bfkey = bfopen((char *)salt, 8);
	memcpy(out, "VimCrypt~03!", 12);
	memcpy(out + 12, salt, 8);
	memcpy(out + 20, seed, 8);
	/* cfb: each ciphertext block is the encrypted previous ciphertext block xor the plaintext */
	for(int offset = 0; offset < len; offset += 8) {
		memcpy(block, out + 20 + offset, 8);
		BF_encrypt((unsigned int *)block, bfkey);
		xor_bytes(out + 28 + offset, block, (char *)text + offset, len - offset < 8 ? len - offset : 8);
	}
}

/* write an encrypted vault file, with a different salt and seed each time */
static void write_vault(const char *rel, const char *text)
{
	static unsigned int files;
	char salt[9], seed[9], *data;
	int len = strlen(text);

	snprintf(salt, sizeof(salt), "salt%04u", files % 10000);
	snprintf(seed, sizeof(seed), "seed%04u", files++ % 10000);
	data = nm_malloc(28 + len);
	encrypt_vault(data, salt, seed, text, len);
	write_file(rel, data, 28 + len);
	free(data);
}

/* load a vault like naemon does, return "OK: name=value ..." or "ERROR: <log>" */
static const char *load(const char *root, const char *options)
{
	static char result[16384];
	char args[PATH_MAX + 256];
	nebstruct_vault_macro_data data;
	size_t len;
	FILE *fp;

	if(truncate(logpath, 0) != 0 && errno != ENOENT) {
		printf("Bail out! cannot truncate %s\n", logpath);
		exit(1);
	}
	snprintf(args, sizeof(args), "vault=%s/%s password=test %s", workdir, root, options);

	if(parse_args(args) == OK && parse_vault() == OK) {
		/* look every macro up through the callback naemon uses */
		len = snprintf(result, sizeof(result), "OK:");
		for(int i = 0; i < macro_store->kv_pairs && len < sizeof(result); i++) {
			memset(&data, 0, sizeof(data));
			data.macro_name = macro_store->kv[i].key;
			handle_vault_macro(NEBCALLBACK_VAULT_MACRO_DATA, &data);
			len += snprintf(result + len, sizeof(result) - len, " %s=%s", data.macro_name, data.value ? data.value : "(null)");
			free(data.value);
		}
	} else {
		len = snprintf(result, sizeof(result), "ERROR: ");
		if((fp = fopen(logpath, "r"))) {
			len += fread(result + len, 1, sizeof(result) - len - 1, fp);
			fclose(fp);
		}
		result[len] = '\0';
	}
	kvvec_destroy(macro_store, KVVEC_FREE_ALL);
	macro_store = NULL;
	return result;
}

/* expect either the exact "OK: ..." result or "ERROR: <part of the log message>" */
static void check(const char *name, const char *root, const char *options, const char *expected)
{
	const char *got = load(root, options);
	int success;

	if(strncmp(expected, "ERROR: ", 7) == 0)
		success = strncmp(got, "ERROR: ", 7) == 0 && strstr(got, expected + 7) != NULL;
	else
		success = strcmp(got, expected) == 0;
	if(!ok(success, name))
		printf("#   expected: %s\n#   got:      %s\n", expected, got);
}

static void test_vim_compatibility(const char *kat_dir)
{
	char path[PATH_MAX], name[128], expected[64], data[64], generated[64];
	size_t size;
	FILE *fp;

	for(size_t i = 0; i < ARRAY_SIZE(kat); i++) {
		int len = strlen(kat[i].text);

		snprintf(path, sizeof(path), "%s/%s", kat_dir, kat[i].file);
		if(!(fp = fopen(path, "r"))) {
			printf("Bail out! cannot read %s\n", path);
			exit(1);
		}
		size = fread(data, 1, sizeof(data), fp);
		fclose(fp);

		/* the generator must produce exactly what vim wrote, given vim's salt and seed */
		encrypt_vault(generated, data + 12, data + 20, kat[i].text, len);
		snprintf(name, sizeof(name), "Key derivation: generator writes the same bytes as vim for %s", kat[i].file);
		if(!ok(size == (size_t)28 + len && memcmp(data, generated, size) == 0, name)) {
			printf("Bail out! generated vault files would not be vim compatible\n");
			exit(1);
		}

		/* and the module must decrypt vim's file */
		write_file(kat[i].file, data, size);
		snprintf(name, sizeof(name), "Every partial block length: vim file %s (%d bytes) decrypts", kat[i].file, len);
		snprintf(expected, sizeof(expected), "OK: VAULT1=%.*s", len - 10, kat[i].text + 9);
		check(name, kat[i].file, "", expected);
	}
	check("wrong password", "16.cfg", "password=wrong", "ERROR: 16.cfg");
}

static void test_single_file(void)
{
	char plain[] = "$VAULT1$=this is a plaintext file and must not be accepted\n";
	char unsupported[40] = "VimCrypt~02!";

	write_vault("macros.cfg", "# comment\n\n$VAULT1$=one\n$VAULT:EXAMPLE$=not only numbers...\n$VAULT2$=a=b\n");
	check("macros, comments and blank lines", "macros.cfg", "", "OK: VAULT1=one VAULT:EXAMPLE=not only numbers... VAULT2=a=b");
	write_vault("blank.cfg", "$VAULT1$= leading blank\n");
	check("a blank after = belongs to the value", "blank.cfg", "", "OK: VAULT1= leading blank");

	write_vault("noequal.cfg", "$VAULT1$\n");
	check("parse error: no =", "noequal.cfg", "", "ERROR: parse error in vault file");
	write_vault("novalue.cfg", "$VAULT1$=\n");
	check("parse error: empty value", "novalue.cfg", "", "ERROR: parse error in vault file");
	write_vault("blankname.cfg", "$VAULT1$ =x\n");
	check("parse error: blank before =", "blankname.cfg", "", "ERROR: parse error in vault file");
	write_vault("user.cfg", "$USER1$=x\n");
	check("parse error: not a $VAULT macro", "user.cfg", "", "ERROR: parse error in vault file");

	write_file("plain.cfg", plain, strlen(plain));
	check("plaintext file", "plain.cfg", "", "ERROR: is not a vim crypted file");
	write_file("unsupported.cfg", unsupported, sizeof(unsupported));
	check("unsupported crypt method", "unsupported.cfg", "", "ERROR: uses unsupported crypt method");
	check("missing file", "missing.cfg", "", "ERROR: cannot read vault file");
}

static int remove_entry(const char *path, const struct stat *st, int flag, struct FTW *ftw)
{
	return remove(path);
}

int main(void)
{
	const char *srcdir = getenv("srcdir");
	char *kat_dir;

	setvbuf(stdout, NULL, _IOLBF, 0);
	if(!mkdtemp(workdir)) {
		printf("Bail out! cannot create %s\n", workdir);
		return 1;
	}
	kat_dir = nspath_absolute(mkstr("%s/tests/vim", srcdir ? srcdir : "."), NULL);
	snprintf(logpath, sizeof(logpath), "%s/naemon.log", workdir);
	log_file = logpath;
	logging_options = ~0UL;
	use_syslog = FALSE;
	daemon_mode = TRUE;

	/* relative paths must never depend on the working directory */
	if(chdir("/") != 0)
		return 1;

	test_vim_compatibility(kat_dir);
	test_single_file();

	close_log_file();
	nftw(workdir, remove_entry, 16, FTW_DEPTH | FTW_PHYS);
	free(kat_dir);
	printf("1..%d\n", tests);
	return failures ? 1 : 0;
}
